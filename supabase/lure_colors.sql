  fish text not null,
  water text not null check (water in ('清澈', '微浑', '浑浊', '肥水')),
  family text not null check (family in ('银白', '红头金', '草黄', '暗色', '橙红')),
  weight smallint not null check (weight between 1 and 100),
  primary key (fish, water, family)
);

alter table public.lure_color_weights enable row level security;

drop policy if exists lure_color_weights_select on public.lure_color_weights;
create policy lure_color_weights_select on public.lure_color_weights
  for select to anon, authenticated using (true);

grant select on public.lure_color_weights to anon, authenticated;

